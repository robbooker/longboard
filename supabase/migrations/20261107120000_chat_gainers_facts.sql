-- #371 Gainers Table: company facts for the stocks in the gainers room, looked up once and kept.
--
--  * chat_gainers_facts: one row per ticker: country, estimated current cash and months of cash left
--    (or "cash flow positive"), and institutional ownership, each with when it was last looked up.
--    Written only by the lookup program on Rob's computer through /api/chat/gainers/facts (its own
--    token, CHAT_GAINERS_LOOKUP_TOKEN); read only by server code, for members who can open the
--    gainers room (/api/chat/gainers/table). RLS on, no policies, service role only.
--  * A value is never replaced by an empty one. The country is never looked up again once known;
--    the cash is looked up again when it is more than 30 days old (the route decides that).
--    not_found marks a ticker DilutionTracker has no page for; the route tries it again later.
--  * chat_gainers_table(day): one row per ticker that alerted in the gainers room that Eastern day,
--    with its facts. Same rule as the nightly page (scripts/gainers-daily/run.py): after-hours alerts
--    are left out and a stock counts once an alert shows at least 150,000 shares.
--  * save_chat_gainers_facts: the only write.
--  * Seeded with the 331 countries already saved in company-countries.json (DilutionTracker, checked
--    2026-10-31 to 2026-11-05). Cash and ownership for those are looked up the first time they alert.
--
-- Additive: nothing existing changes. Apply before the app that shows the table ships.
-- Rollback: supabase/rollbacks/20261107120000_chat_gainers_facts.down.sql

create table public.chat_gainers_facts(
 ticker text primary key check(ticker ~ '^[A-Z][A-Z. ]{0,11}$'),
 country text check(country is null or char_length(country) between 1 and 60),
 country_checked_at timestamptz,
 cash_usd numeric check(cash_usd is null or cash_usd between 0 and 1e13),
 cash_months_left numeric check(cash_months_left is null or cash_months_left between 0 and 1e6),
 cash_flow_positive boolean not null default false,
 cash_checked_at timestamptz,
 inst_own_pct numeric check(inst_own_pct is null or inst_own_pct between 0 and 1000),
 inst_own_checked_at timestamptz,
 not_found boolean not null default false,
 source text not null default 'dilutiontracker.com' check(char_length(source) between 1 and 60),
 checked_at timestamptz not null default now(),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
alter table public.chat_gainers_facts enable row level security;
revoke all on public.chat_gainers_facts from public,anon,authenticated,service_role;
grant select,insert,update on public.chat_gainers_facts to service_role;

create function public.chat_gainers_table(p_day date)
returns table(ticker text,last_alert_at timestamptz,alerts integer,country text,country_checked_at timestamptz,
 cash_usd numeric,cash_months_left numeric,cash_flow_positive boolean,cash_checked_at timestamptz,
 inst_own_pct numeric,inst_own_checked_at timestamptz,not_found boolean,checked_at timestamptz)
language sql stable set search_path='' as $$
 with bounds as (
  select (p_day::timestamp at time zone 'America/New_York') s,((p_day+1)::timestamp at time zone 'America/New_York') f
 ), alerts as (
  select substring(m.body from '^🚨 ([A-Z. ]+?) \(\+') sym,
   coalesce(replace(substring(m.body from 'Volume: ([0-9,]{1,20})'),',','')::numeric,0) vol,m.created_at
  from public.longboard_chat_messages m,bounds b
  where m.room_slug='gainers' and m.reply_to_id is null and not m.removed
   and m.created_at>=b.s and m.created_at<b.f and position('After-Hours' in m.body)=0
 ), stocks as (
  select a.sym,max(a.created_at) last_at,count(*)::integer n from alerts a
  where a.sym is not null group by a.sym having max(a.vol)>=150000
 )
 select s.sym,s.last_at,s.n,f.country,f.country_checked_at,f.cash_usd,f.cash_months_left,coalesce(f.cash_flow_positive,false),
  f.cash_checked_at,f.inst_own_pct,f.inst_own_checked_at,coalesce(f.not_found,false),f.checked_at
 from stocks s left join public.chat_gainers_facts f on f.ticker=s.sym
 order by s.last_at desc,s.sym limit 500;
$$;
revoke all on function public.chat_gainers_table(date) from public,anon,authenticated;
grant execute on function public.chat_gainers_table(date) to service_role;

-- One lookup's result. p_not_found: DilutionTracker had no page for the ticker; only that is noted.
create function public.save_chat_gainers_facts(p_ticker text,p_country text,p_cash_usd numeric,p_cash_months_left numeric,
 p_cash_flow_positive boolean,p_inst_own_pct numeric,p_not_found boolean)
returns void language plpgsql security invoker set search_path='' as $$
begin
 if p_not_found then
  insert into public.chat_gainers_facts as f(ticker,not_found,checked_at) values(p_ticker,true,now())
  on conflict(ticker) do update set not_found=f.country is null and f.cash_checked_at is null and f.inst_own_checked_at is null,
   checked_at=now(),updated_at=now();
  return;
 end if;
 insert into public.chat_gainers_facts as f(ticker,country,country_checked_at,cash_usd,cash_months_left,cash_flow_positive,cash_checked_at,
  inst_own_pct,inst_own_checked_at,not_found,checked_at)
 values(p_ticker,p_country,now(),p_cash_usd,case when p_cash_flow_positive then null else p_cash_months_left end,
  coalesce(p_cash_flow_positive,false),now(),p_inst_own_pct,now(),false,now())
 on conflict(ticker) do update set
  -- A country, once known, stays (it never needs a refresh).
  country=coalesce(f.country,excluded.country),
  country_checked_at=case when f.country is not null then f.country_checked_at else now() end,
  -- New cash replaces old only when the page said something about it.
  cash_usd=case when excluded.cash_usd is not null or excluded.cash_flow_positive then excluded.cash_usd else f.cash_usd end,
  cash_months_left=case when excluded.cash_usd is not null or excluded.cash_flow_positive then excluded.cash_months_left else f.cash_months_left end,
  cash_flow_positive=case when excluded.cash_usd is not null or excluded.cash_flow_positive then excluded.cash_flow_positive else f.cash_flow_positive end,
  cash_checked_at=now(),
  inst_own_pct=coalesce(excluded.inst_own_pct,f.inst_own_pct),
  inst_own_checked_at=now(),
  not_found=false,checked_at=now(),updated_at=now();
end $$;
revoke all on function public.save_chat_gainers_facts(text,text,numeric,numeric,boolean,numeric,boolean) from public,anon,authenticated;
grant execute on function public.save_chat_gainers_facts(text,text,numeric,numeric,boolean,numeric,boolean) to service_role;

